/*
 * luna-berry.c — BeASM / Berry OS artifact emitter.
 */

#include "luna-berry.h"

#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "luna-common.h"
#include "luna-opt.h"

static void luna_berry_err(char *err, size_t errlen, const char *fmt, ...)
{
    va_list ap;
    if (err == NULL || errlen == 0)
        return;
    va_start(ap, fmt);
    vsnprintf(err, errlen, fmt, ap);
    va_end(ap);
}

static void luna_berry_emit_bytes(FILE *f, const unsigned char *bc, size_t len)
{
    size_t i;
    if (len == 0) {
        fprintf(f, "luna_app_bytecode db 0x00\n");
        return;
    }
    for (i = 0; i < len; i++) {
        if (i % 16 == 0)
            fprintf(f, i == 0 ? "luna_app_bytecode db " : "db ");
        fprintf(f, "0x%02x", bc[i]);
        if (i % 16 == 15 || i + 1 == len)
            fprintf(f, "\n");
        else
            fprintf(f, ", ");
    }
}

static int luna_berry_write_basm(const char *path, const unsigned char *bc,
                                 size_t len)
{
    FILE *f = fopen(path, "wb");
    if (f == NULL)
        return -1;

    fprintf(f,
            "; generated by LunaAOT (Berry backend) — LunaBerry in BeASM\n"
            "; package: " LUNA_PACKAGE_NAME "\n"
            "; bytecode: %lu bytes (lunac output; runs via luna_berry_eval_binary)\n"
            "\n"
            "section '.data' data readable\n\n",
            (unsigned long)len);
    luna_berry_emit_bytes(f, bc, len);
    fprintf(f,
            "luna_app_bytecode_len = $ - luna_app_bytecode\n"
            "\n"
            "; LunaBerryEngine (platform/berry/luna_berry.h) — state + budgets\n"
            "luna_engine resq 16\n"
            "\n"
            "BERRY_IMPORT luna_berry_init, luna_berry_eval_binary, luna_berry_loop, luna_berry_destroy\n"
            "luna_runtime dq luna_berry_init\n"
            "dq luna_berry_eval_binary\n"
            "dq luna_berry_loop\n"
            "dq luna_berry_destroy\n"
            "dq 0\n"
            "\n"
            "section '.text' code executable\n"
            "\n"
            "luna_app_entry:\n"
            "    push rbp\n"
            "    mov rbp, rsp\n"
            "    sub rsp, 32\n"
            "    lea rdi, [rel luna_engine]\n"
            "    mov rsi, 0\n"
            "    mov rdx, 0\n"
            "    call [rel luna_runtime]\n"
            "    test rax, rax\n"
            "    jnz .entry_fail\n"
            "    lea rdi, [rel luna_engine]\n"
            "    lea rsi, [rel luna_app_bytecode]\n"
            "    mov rdx, luna_app_bytecode_len\n"
            "    call [rel luna_runtime + 8]\n"
            "    test rax, rax\n"
            "    jnz .entry_fail\n"
            "    lea rdi, [rel luna_engine]\n"
            "    call [rel luna_runtime + 16]\n"
            ".entry_done:\n"
            "    lea rdi, [rel luna_engine]\n"
            "    call [rel luna_runtime + 24]\n"
            "    xor rax, rax\n"
            "    leave\n"
            "    ret\n"
            ".entry_fail:\n"
            "    mov rax, 1\n"
            "    jmp .entry_done\n"
            "\n"
            "main:\n"
            "    push rbp\n"
            "    mov rbp, rsp\n"
            "    call luna_app_entry\n"
            "    leave\n"
            "    ret\n"
            "\n"
            "section '.exports' data readable\n"
            "\n"
            "BERRY_EXPORT luna_app_entry, 1\n"
            "\n"
            "dd 0, 0, 0\n");
    return fclose(f) == 0 ? 0 : -1;
}

static int luna_berry_write_host(const char *path, const unsigned char *bc,
                                 size_t len)
{
    FILE *f = fopen(path, "wb");
    if (f == NULL)
        return -1;

    fprintf(f,
            "/* generated by LunaAOT (Berry host verification) */\n"
            "#include <stdio.h>\n"
            "#include \"luna_berry.h\"\n\n");
    luna_emit_c_array(f, "luna_app_bytecode", bc, len);
    fprintf(f,
            "\nint main(void)\n"
            "{\n"
            "    LunaBerryEngine e;\n"
            "    if (luna_berry_init(&e, 0, 0) != 0) {\n"
            "        fprintf(stderr, \"berry: init failed\\n\");\n"
            "        return 1;\n"
            "    }\n"
            "    if (luna_berry_eval_binary(&e, luna_app_bytecode,\n"
            "                               luna_app_bytecode_len) != 0) {\n"
            "        fprintf(stderr, \"berry: %%s\\n\",\n"
            "                luna_last_error(e.state));\n"
            "        luna_berry_destroy(&e);\n"
            "        return 1;\n"
            "    }\n"
            "    luna_berry_loop(&e);\n"
            "    luna_berry_destroy(&e);\n"
            "    return 0;\n"
            "}\n");
    return fclose(f) == 0 ? 0 : -1;
}

static int luna_find_beasm(const char *hint, const char *root, char *out,
                           size_t out_size)
{
    char dir[1024];
    char cand[1200];
    const char *names[] = { "beasm.exe", "beasm" };
    size_t i;

    if (hint != NULL && hint[0] != '\0') {
        if (luna_file_exists(hint)) {
            snprintf(out, out_size, "%s", hint);
            return 0;
        }
        return -1;
    }

    luna_exe_dir(dir, sizeof(dir));
    for (i = 0; i < 2; i++) {
        luna_path_join(cand, sizeof(cand), dir, names[i]);
        if (luna_file_exists(cand)) {
            snprintf(out, out_size, "%s", cand);
            return 0;
        }
    }
    for (i = 0; i < 2; i++) {
        char tools[1200];
        luna_path_join(tools, sizeof(tools), root, "tools/beasm");
        luna_path_join(cand, sizeof(cand), tools, names[i]);
        if (luna_file_exists(cand)) {
            snprintf(out, out_size, "%s", cand);
            return 0;
        }
    }
    return -1;
}

int luna_berry_emit(const unsigned char *bc, size_t len, const char *stem,
                    const LunaBerryOptions *opts, char *err, size_t errlen)
{
    char out_dir[1024];
    char base[1200];
    char lbc[1400];
    char basm[1400];
    char bex[1400];
    char host[1400];
    char host_c[1400];
    char lib_dir[1024];
    char lib[1200];
    char beasm[1200];
    char cmd[6000];
    char outbuf[2048];
    const char *root = opts != NULL && opts->include_dir ? opts->include_dir : ".";
    int emit_host = opts != NULL ? opts->emit_host : 1;
    int verbose = opts != NULL ? opts->verbose : 0;

    if (err != NULL && errlen > 0)
        err[0] = '\0';
    if (bc == NULL || len == 0) {
        luna_berry_err(err, errlen, "empty bytecode");
        return -1;
    }

    snprintf(out_dir, sizeof(out_dir), "%s",
             opts != NULL && opts->out_dir ? opts->out_dir : "dist/berry");
    luna_mkdir_p(out_dir);

    luna_path_join(base, sizeof(base), out_dir, stem);
    snprintf(lbc, sizeof(lbc), "%s.lbc", base);
    snprintf(basm, sizeof(basm), "%s.basm", base);
    snprintf(bex, sizeof(bex), "%s.bex", base);
    snprintf(host_c, sizeof(host_c), "%s.host.c", base);
#if defined(_WIN32)
    snprintf(host, sizeof(host), "%s.host.exe", base);
#else
    snprintf(host, sizeof(host), "%s.host", base);
#endif

    if (luna_write_file(lbc, bc, len) != 0) {
        luna_berry_err(err, errlen, "cannot write %s", lbc);
        return -1;
    }
    if (luna_berry_write_basm(basm, bc, len) != 0) {
        luna_berry_err(err, errlen, "cannot write %s", basm);
        return -1;
    }

    if (luna_find_beasm(opts != NULL ? opts->beasm : NULL, root, beasm,
                        sizeof(beasm)) == 0) {
        snprintf(cmd, sizeof(cmd), "\"%s\" \"%s\" -o \"%s\" --format bex --entry luna_app_entry",
                 beasm, basm, bex);
        if (verbose)
            fprintf(stderr, "  %s\n", cmd);
        if (luna_run_cmd(cmd, outbuf, sizeof(outbuf)) != 0)
            fprintf(stderr, "berry: beasm failed (module still valid): %s\n", outbuf);
    } else {
        fprintf(stderr, "berry: beasm not found; wrote .basm and .lbc only\n");
    }

    if (emit_host) {
        if (luna_berry_write_host(host_c, bc, len) != 0) {
            luna_berry_err(err, errlen, "cannot write %s", host_c);
            return -1;
        }
        if (opts != NULL && opts->lib_dir != NULL) {
            snprintf(lib_dir, sizeof(lib_dir), "%s", opts->lib_dir);
        } else {
            luna_exe_dir(lib_dir, sizeof(lib_dir));
        }
        snprintf(lib, sizeof(lib), "%s/liblunaberry.a", lib_dir);
        {
            char cc[1200];
#if defined(_WIN32)
            const char *want = "gcc";
#else
            const char *want = "cc";
#endif
            if (luna_find_tool(want, cc, sizeof(cc)) != 0)
                snprintf(cc, sizeof(cc), "%s", want);
            snprintf(cmd, sizeof(cmd),
                     "\"%s\" %s -I\"%s\" -I\"%s/platform/berry\" "
                     "-o \"%s\" \"%s\" \"%s\" -lm",
                     cc, luna_opt_flags(opts != NULL ? opts->opt_level : -1),
                     root, root, host, host_c, lib);
        }
        if (verbose)
            fprintf(stderr, "  %s\n", cmd);
        if (luna_run_cmd(cmd, outbuf, sizeof(outbuf)) != 0) {
            luna_berry_err(err, errlen, "host link failed: %s", outbuf);
            remove(host_c);
            return -1;
        }
        remove(host_c);
        if (luna_opt_implies_strip(opts != NULL ? opts->opt_level : -1)) {
            if (luna_opt_strip_binary(host) == 0 && verbose)
                fprintf(stderr, "  stripped %s\n", host);
        }
    }

    return 0;
}

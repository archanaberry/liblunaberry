/*
 * luna-llvm.c — LLVM/clang AOT connector for LunaBerry.
 */

#include "luna-llvm.h"

#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "luna-common.h"

static void luna_llvm_err(char *err, size_t errlen, const char *fmt, ...)
{
    va_list ap;
    if (err == NULL || errlen == 0)
        return;
    va_start(ap, fmt);
    vsnprintf(err, errlen, fmt, ap);
    va_end(ap);
}

static const char *luna_clang_default(char *buf, size_t bufsize)
{
    const char *c = getenv("CLANG");
    if (c != NULL && c[0] != '\0')
        return c;
    if (luna_find_tool("clang", buf, bufsize) == 0)
        return buf;
    return "clang";
}

int luna_llvm_available(void)
{
    char cmd[4096];
    char tool[2048];
    const char *clang = luna_clang_default(tool, sizeof(tool));
    snprintf(cmd, sizeof(cmd), "\"%s\" --version", clang);
    return luna_run_cmd(cmd, NULL, 0) == 0;
}

/* Locate LLVM's `opt` next to clang, then in PATH.  Returns NULL when the
 * host has no standalone optimizer (the common case for a bare clang
 * install), and the caller falls back to a clang -x ir round trip. */
static const char *luna_llvm_find_opt(char *buf, size_t bufsize)
{
    static char cached[2100];
    static int  cached_done = 0;
    const char *clang = luna_clang_default(buf, bufsize);
    if (!cached_done) {
        char cand[2100];
        char dir[2048];
        char *slash;
        cached_done = 1;
        cached[0] = '\0';
        snprintf(dir, sizeof(dir), "%s", clang);
        slash = (char *)strrchr(dir, '/');
        if (slash == NULL)
            slash = (char *)strrchr(dir, '\\');
        if (slash != NULL) {
            slash[1] = '\0';
            snprintf(cand, sizeof(cand), "%sopt.exe", dir);
            if (luna_file_exists(cand)) {
                snprintf(cached, sizeof(cached), "%s", cand);
                return cached;
            }
            snprintf(cand, sizeof(cand), "%sopt", dir);
            if (luna_file_exists(cand)) {
                snprintf(cached, sizeof(cached), "%s", cand);
                return cached;
            }
        }
        if (luna_find_tool("opt", cached, sizeof(cached)) == 0)
            return cached;
        return NULL;
    }
    return cached[0] != '\0' ? cached : NULL;
}

/* Extract the clang -O level out of a flag string (default 2). */
static int luna_llvm_o_level(const char *flags)
{
    const char *p = flags;
    int level = -1;
    if (flags == NULL)
        return 2;
    while (*p != '\0') {
        if (p[0] == '-' && p[1] == 'O' && p[2] >= '0' && p[2] <= '3') {
            /* accept -O0..-O3 (also -Os/-Oz -> treat as 2) */
            int v = p[2] - '0';
            if (level < 0 || v > level)
                level = v;
        }
        p++;
    }
    return level < 0 ? 2 : level;
}

static int luna_llvm_write_wrapper(const char *c_path, const unsigned char *bc,
                                   size_t len)
{
    FILE *f = fopen(c_path, "wb");
    if (f == NULL)
        return -1;

    fprintf(f,
            "/* generated by LunaAOT (LLVM backend) — do not edit */\n"
            "#include <stdio.h>\n"
            "#include \"luna.h\"\n\n");
    luna_emit_c_array(f, "luna_bc", bc, len);
    fprintf(f,
            /* main must stay visible when the wrapper is compiled with
             * -fvisibility=hidden (ladder level 7+) on ELF targets. */
            "\n#if defined(__GNUC__) && !defined(_WIN32)\n"
            "__attribute__((visibility(\"default\")))\n"
            "#endif\n"
            "int main(int argc, char **argv)\n"
            "{\n"
            "    LunaOptions o;\n"
            "    LunaState *s;\n"
            "    int i, n;\n"
            "    (void)argc; (void)argv;\n"
            "    o.mem_limit = 0;\n"
            "    o.open_libs = 1;\n"
            "    o.name = \"@aot\";\n"
            "    s = luna_new(&o);\n"
            "    if (s == NULL) {\n"
            "        fprintf(stderr, \"luna: cannot create state\\n\");\n"
            "        return 1;\n"
            "    }\n"
            "    if (luna_dobytecode(s, luna_bc, luna_bc_len, \"@aot\") != 0) {\n"
            "        fprintf(stderr, \"luna: %%s\\n\", luna_last_error(s));\n"
            "        luna_free(s);\n"
            "        return 1;\n"
            "    }\n"
            "    n = luna_result_count(s);\n"
            "    for (i = 1; i <= n; i++) {\n"
            "        int t = luna_result_type(s, i);\n"
            "        if (i > 1) printf(\"\\t\");\n"
            "        if (t == 1) printf(\"%%.14g\", luna_result_number(s, i));\n"
            "        else if (t == 2) printf(\"%%s\", luna_result_string(s, i));\n"
            "        else if (t == 3) printf(\"%%s\", luna_result_boolean(s, i) ? \"true\" : \"false\");\n"
            "        else if (t == 0) printf(\"nil\");\n"
            "        else printf(\"<value>\");\n"
            "    }\n"
            "    if (n > 0) printf(\"\\n\");\n"
            "    luna_free(s);\n"
            "    return 0;\n"
            "}\n");
    return fclose(f) == 0 ? 0 : -1;
}

static void luna_llvm_target_flags(char *out, size_t out_size)
{
    out[0] = '\0';
#if defined(_WIN32)
    {
        char inc[1024];
        if (luna_mingw_include(inc, sizeof(inc)) == 0)
            snprintf(out, out_size,
                     "--target=x86_64-w64-windows-gnu -isystem \"%s\"", inc);
    }
#else
    (void)out;
    (void)out_size;
#endif
}

static int luna_llvm_run(const char *cmd, int verbose, char *err,
                         size_t errlen)
{
    char out[2048];
    int rc;
    if (verbose)
        fprintf(stderr, "  %s\n", cmd);
    rc = luna_run_cmd(cmd, out, sizeof(out));
    if (rc != 0) {
        luna_llvm_err(err, errlen, "clang failed (%d): %s", rc, out);
        return -1;
    }
    return 0;
}

int luna_llvm_emit_c(const unsigned char *bc, size_t len, const char *out_c,
                     char *err, size_t errlen)
{
    if (luna_llvm_write_wrapper(out_c, bc, len) != 0) {
        if (err != NULL && errlen > 0)
            snprintf(err, errlen, "cannot write %s", out_c);
        return -1;
    }
    return 0;
}

int luna_llvm_emit_asm(const unsigned char *bc, size_t len, const char *out_s,
                       const char *chunk_name, const LunaLLvmOptions *opts,
                       char *err, size_t errlen)
{
    char c_path[1200];
    char cmd[8192];
    char tflags[1400];
    char tool[2048];
    const char *clang = opts != NULL && opts->clang ? opts->clang
                                                   : luna_clang_default(tool, sizeof(tool));
    const char *flags = opts != NULL && opts->flags ? opts->flags : "-O2";
    const char *inc = opts != NULL && opts->include_dir ? opts->include_dir : ".";

    (void)chunk_name;
    if (err != NULL && errlen > 0)
        err[0] = '\0';

    snprintf(c_path, sizeof(c_path), "%s.luna.c", out_s);
    if (luna_llvm_write_wrapper(c_path, bc, len) != 0) {
        luna_llvm_err(err, errlen, "cannot write %s", c_path);
        return -1;
    }
    luna_llvm_target_flags(tflags, sizeof(tflags));
    snprintf(cmd, sizeof(cmd), "\"%s\" %s %s -S -I\"%s\" -o \"%s\" \"%s\"",
             clang, tflags, flags, inc, out_s, c_path);
    if (luna_llvm_run(cmd, opts != NULL ? opts->verbose : 0, err, errlen) != 0) {
        remove(c_path);
        return -1;
    }
    remove(c_path);
    return 0;
}

int luna_llvm_emit_ir(const unsigned char *bc, size_t len, const char *out_ll,
                      const char *chunk_name, const LunaLLvmOptions *opts,
                      char *err, size_t errlen)
{
    char c_path[1200];
    char cmd[8192];
    char tflags[1400];
    char tool[2048];
    const char *clang = opts != NULL && opts->clang ? opts->clang
                                                   : luna_clang_default(tool, sizeof(tool));
    const char *flags = opts != NULL && opts->flags ? opts->flags : "-O2";
    const char *inc = opts != NULL && opts->include_dir ? opts->include_dir : ".";
    int verbose = opts != NULL ? opts->verbose : 0;

    (void)chunk_name;
    if (err != NULL && errlen > 0)
        err[0] = '\0';

    snprintf(c_path, sizeof(c_path), "%s.luna.c", out_ll);
    if (luna_llvm_write_wrapper(c_path, bc, len) != 0) {
        luna_llvm_err(err, errlen, "cannot write %s", c_path);
        return -1;
    }
    luna_llvm_target_flags(tflags, sizeof(tflags));
    snprintf(cmd, sizeof(cmd),
             "\"%s\" %s %s -S -emit-llvm -I\"%s\" -o \"%s\" \"%s\"",
             clang, tflags, flags, inc, out_ll, c_path);
    if (luna_llvm_run(cmd, verbose, err, errlen) != 0) {
        remove(c_path);
        return -1;
    }
    remove(c_path);
    return 0;
}

/* Run the ladder's new-PM pipeline over an .ll file.
 *   opt present : "opt" -passes="<pipeline>" -S in.ll -o out.ll
 *   no opt      : clang round trip, "clang" -x ir in.ll -O<N> -S -emit-llvm
 *                 (the clang optimizer runs the equivalent default pipeline)
 * Returns 0 on success, -1 on failure (err is filled). */
static int luna_llvm_run_passes(const char *clang, const char *ll_in,
                                const char *ll_out, const char *pipeline,
                                const char *flags, int verbose, char *err,
                                size_t errlen)
{
    char cmd[8192];
    char tool[2048];
    const char *opt = luna_llvm_find_opt(tool, sizeof(tool));

    if (opt != NULL) {
        snprintf(cmd, sizeof(cmd),
                 "\"%s\" -passes=\"%s\" -S \"%s\" -o \"%s\"",
                 opt, pipeline != NULL ? pipeline : "default<O2>", ll_in,
                 ll_out);
    } else {
        /* No standalone optimizer on this host: round-trip the IR through
         * the clang front end, which runs its default pass pipeline at the
         * requested -O level. */
        int o = luna_llvm_o_level(flags);
        snprintf(cmd, sizeof(cmd),
                 "\"%s\" -x ir \"%s\" -O%d -S -emit-llvm -o \"%s\"",
                 clang, ll_in, o, ll_out);
    }
    return luna_llvm_run(cmd, verbose, err, errlen);
}

int luna_llvm_aot(const unsigned char *bc, size_t len, const char *out_exe,
                  const char *chunk_name, const LunaLLvmOptions *opts,
                  char *err, size_t errlen)
{
    char c_path[1200];
    char ll_path[1200];
    char ll_opt[1200];
    char cmd[8192];
    char tflags[1400];
    char dir[1024];
    char lib[1200];
    char tool[2048];
    char xflags[1400];
    const char *clang = opts != NULL && opts->clang ? opts->clang
                                                   : luna_clang_default(tool, sizeof(tool));
    const char *flags = opts != NULL && opts->flags ? opts->flags : "-O2";
    const char *inc = opts != NULL && opts->include_dir ? opts->include_dir : ".";
    const char *lib_dir = opts != NULL && opts->lib_dir ? opts->lib_dir : NULL;
    const char *passes = opts != NULL ? opts->passes : NULL;
    int emit_ir = opts != NULL ? opts->emit_ir : 0;
    int verbose = opts != NULL ? opts->verbose : 0;
    int want_lto = opts != NULL ? opts->lto : 0;
    int want_gc = opts != NULL ? opts->gc_sections : 0;
    int want_passes = opts != NULL ? opts->ir_passes : 0;
    int rc;

    (void)chunk_name;
    if (err != NULL && errlen > 0)
        err[0] = '\0';

    if (lib_dir == NULL) {
        luna_exe_dir(dir, sizeof(dir));
        lib_dir = dir;
    }
    snprintf(lib, sizeof(lib), "%s/liblunaberry.a", lib_dir);

    snprintf(c_path, sizeof(c_path), "%s.luna.c", out_exe);
    snprintf(ll_path, sizeof(ll_path), "%s.ll", out_exe);
    snprintf(ll_opt, sizeof(ll_opt), "%s.opt.ll", out_exe);

    /* Assemble the full clang flag set. */
    snprintf(xflags, sizeof(xflags), "%s", flags);
    if (want_lto)
        snprintf(xflags + strlen(xflags), sizeof(xflags) - strlen(xflags),
                 " -flto=thin");
    if (want_gc)
        snprintf(xflags + strlen(xflags), sizeof(xflags) - strlen(xflags),
                 " -ffunction-sections -fdata-sections -Wl,--gc-sections");

    if (luna_llvm_write_wrapper(c_path, bc, len) != 0) {
        luna_llvm_err(err, errlen, "cannot write %s", c_path);
        return -1;
    }

    luna_llvm_target_flags(tflags, sizeof(tflags));

    if (emit_ir || want_passes) {
        /* 1. C -> textual IR */
        snprintf(cmd, sizeof(cmd),
                 "\"%s\" %s %s -S -emit-llvm -I\"%s\" -o \"%s\" \"%s\"",
                 clang, tflags, xflags, inc, ll_path, c_path);
        if (luna_llvm_run(cmd, verbose, err, errlen) != 0) {
            remove(c_path);
            return -1;
        }
        /* 2. optional IR pass pipeline */
        if (want_passes) {
            if (luna_llvm_run_passes(clang, ll_path, ll_opt, passes, xflags,
                                     verbose, err, errlen) != 0) {
                remove(c_path);
                return -1;
            }
            remove(ll_path);
            snprintf(ll_path, sizeof(ll_path), "%s", ll_opt);
        }
        /* 3. IR -> native */
        snprintf(cmd, sizeof(cmd),
                 "\"%s\" %s %s -o \"%s\" \"%s\" \"%s\" -lm",
                 clang, tflags, xflags, out_exe, ll_path, lib);
        rc = luna_llvm_run(cmd, verbose, err, errlen);
        if (rc != 0) {
            remove(c_path);
            return -1;
        }
    } else {
        snprintf(cmd, sizeof(cmd),
                 "\"%s\" %s %s -I\"%s\" -o \"%s\" \"%s\" \"%s\" -lm",
                 clang, tflags, xflags, inc, out_exe, c_path, lib);
        rc = luna_llvm_run(cmd, verbose, err, errlen);
        if (rc != 0) {
            remove(c_path);
            return -1;
        }
    }

    remove(c_path);
    if (!emit_ir)
        remove(ll_path);
    return 0;
}
